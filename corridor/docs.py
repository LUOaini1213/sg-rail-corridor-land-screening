"""Generated documents: the fact sheet, the data-sources page and the README.

URLs are written as code spans, not as hyperlinks: the website terms of SLA, LTA, URA and MinLaw ask for
permission before anyone links to their pages, so their addresses are given as plain-text citations.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import config

FACT_HEADER = """# Fact sheet: land and railway rules used by the screening

> **Not legal advice.** A short, sourced summary prepared for a personal portfolio project. It states what
> the cited public documents say, checked on {accessed}; it is not a statement of the law as it applies to
> any land, and it says nothing about how any agency handles cases internally.

<!-- Generated by scripts/build_docs.py from inputs/facts.yaml. Edit that file, not this page. -->

**How to read it.** *VERIFIED*: the quoted words were found in the cited document. For statutes, Singapore
Statutes Online (SSO) refused automated access (HTTP 403 on its Terms of Use page), so no further automated
request was sent to SSO and no bot challenge was attempted; statutory text was read instead from
SSO-generated "informal consolidation" PDFs held by FAOLEX (FAO), whose in-force dates are given.
*UNVERIFIED*: the document could not be read; the row is a pointer only. Quotes are short extracts for
checking; copyright stays with the publishers. Web addresses are given as plain-text citations rather than
links, because several publishers' website terms ask for permission before linking.

{n_verified} of {n_total} rows are VERIFIED and {n_unverified} UNVERIFIED. Rows marked *used* feed a calculation in
the screening (`corridor.config.fact_value()` refuses UNVERIFIED rows).
"""


def _cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def render_fact_sheet() -> str:
    f = config.facts()
    facts = f["facts"]
    src = f["sources"]
    used = {"F12", "F13", "F14", "F15", "F21"}
    n_ver = sum(1 for r in facts if r["status"] == "VERIFIED")
    out = [FACT_HEADER.format(accessed=f["accessed"], n_verified=n_ver, n_total=len(facts),
                              n_unverified=len(facts) - n_ver)]
    topics: list[str] = []
    for r in facts:
        if r["topic"] not in topics:
            topics.append(r["topic"])
    for t in topics:
        out.append(f"\n## {t}\n")
        out.append("| ID | Claim | Source | Where | Quote | Status |")
        out.append("|---|---|---|---|---|---|")
        for r in facts:
            if r["topic"] != t:
                continue
            status = r["status"] + (" (used)" if r["id"] in used else "")
            quote = f"\"{_cell(r['quote'])}\"" if r["quote"] else "-"
            out.append(f"| {r['id']} | {_cell(r['claim'])} | {r['source']} | {_cell(r['locator'])} | {quote} | "
                       f"{status}<br>{_cell(r['basis'])} |")
    out.append("\n## Sources\n")
    out.append("| ID | Document | Publisher | Address (plain text) | Accessed | SHA-256 of the copy read | Note |")
    out.append("|---|---|---|---|---|---|---|")
    for k, s in src.items():
        sha = f"`{s['sha256'][:16]}...`" if s.get("sha256") else "-"
        out.append(f"| {k} | {_cell(s['title'])} | {_cell(s['publisher'])} | `{s['url']}` | {f['accessed']} | {sha} | "
                   f"{_cell(s.get('note', ''))} |")
    return "\n".join(out) + "\n"


DATA_HEADER = """# Data sources and what is openly available

> Personal portfolio desk study on public data, built with AI assistance; not affiliated with or endorsed by
> LTA, SLA or URA. This page lists every dataset used, when it was downloaded and under what licence, and
> what was looked for but is not openly available.

<!-- Generated by scripts/build_docs.py from data/manifest.json and results/. Edit docs/templates/, not this page. -->
"""


def render_data_sources(results: dict) -> str:
    man = json.loads((config.DATA / "manifest.json").read_text(encoding="utf-8"))
    lines = [DATA_HEADER, "## Datasets downloaded\n",
             "| Key | Dataset | Publisher | Dataset page or service (plain text) | Dataset last updated | Downloaded | Size (bytes) | SHA-256 | Licence |",
             "|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(man):
        m = man[k]
        upd = m.get("dataset_last_updated") or m.get("osm_base") or "-"
        lines.append(f"| `{k}` | {_cell(m['dataset_name'])} | {_cell(m['publisher'])} | `{m['page']}` | {upd} | "
                     f"{m['accessed']} | {m['bytes']:,} | `{m['sha256'][:16]}...` | {m['licence']} |")
    tmpl = (config.DOCS / "templates" / "data_sources.md").read_text(encoding="utf-8")
    return "\n".join(lines) + "\n\n" + render(tmpl, results)


PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.\-]+)\s*(?::\s*([^}]*?))?\s*\}\}")


def lookup(results: dict, path: str):
    cur = results
    for part in path.split("."):
        if isinstance(cur, dict) and part in cur:
            cur = cur[part]
        elif isinstance(cur, list) and part.isdigit():
            cur = cur[int(part)]
        else:
            raise KeyError(path)
    return cur


def fmt(value, spec: str | None) -> str:
    if spec is None or spec == "":
        return str(value)
    if spec == "pct":
        return f"{100 * float(value):.0f}%"
    if spec.startswith("pct"):
        return f"{100 * float(value):.{int(spec[3:])}f}%"
    if spec == "ha":
        return f"{float(value) / 10000:.2f}"
    if spec == "join":
        return ", ".join(str(x) for x in value)
    return format(value, spec)


def render(template: str, results: dict) -> str:
    return PLACEHOLDER.sub(lambda m: fmt(lookup(results, m.group(1)), m.group(2)), template)


def load_results() -> dict:
    out = {}
    for p in sorted(config.RESULTS.glob("*.json")):
        out[p.stem] = json.loads(p.read_text(encoding="utf-8"))
    tables = config.RESULTS / "tables"
    if tables.exists():
        out["tables"] = {p.stem: p.read_text(encoding="utf-8").rstrip("\n") for p in sorted(tables.glob("*.md"))}
    return out


def write_if_changed(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True
